from llama_cpp import Llama

llm = Llama(
    model_path="./models/qwen2.5-3b-instruct-q4_k_m.gguf",
    n_ctx=2048,
    n_threads=8,
    temperature=0.0
)

SYSTEM_PROMPT = """
Ты — строго ограниченный парсер пользовательских команд.
Ты НЕ чат-ассистент, НЕ помощник и НЕ объясняешь ответы.

Твоя задача:
преобразовать текст команды пользователя в JSON для вызова backend-функции.

У тебя есть ТОЛЬКО следующие разрешённые функции:

1) get_orders
Описание: получить список заказов с фильтрами.
Параметры:
- min_sum (number) — минимальная сумма заказа в рублях.

Правила (ОБЯЗАТЕЛЬНЫЕ):
- Ты МОЖЕШЬ использовать ТОЛЬКО перечисленные функции.
- Ты НЕ МОЖЕШЬ придумывать новые функции или параметры.
- Ты НЕ МОЖЕШЬ догадываться или интерпретировать неочевидные запросы.
- Если команда не соответствует ни одной функции — верни null.
- Если параметр не указан явно — верни null.
- Отвечай ТОЛЬКО валидным JSON.
- Никакого текста, пояснений, комментариев или markdown.
- Один ответ — один JSON-объект или null.
- Отвечай ТОЛЬКО JSON и добавляй в конце маркер <END>.


Формат ответа (СТРОГО):

Пример корректного ответа:
{"name":"get_orders","arguments":{"min_sum":100}}<END>

или

null<END>

Любой другой формат ответа считается ошибкой.
"""


# user_text = "дай ссылки на заказы стоимость которых выше ста рублей"
user_text = "ну типа хуй"

prompt = f"""
{SYSTEM_PROMPT}

Команда пользователя:
{user_text}

Ответ:
"""

result = llm(
    prompt,
    max_tokens=64,
    stop=["<END>"]
)

output = result["choices"][0]["text"].strip()
print(output)



